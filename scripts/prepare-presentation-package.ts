import { copyFile, mkdir, writeFile } from 'node:fs/promises'
import path from 'node:path'

const root = process.cwd()
const source = path.join(root, 'ТЕСТОВЫЕ_ДОКУМЕНТЫ_ДЛЯ_ЗАГРУЗКИ')
const destination = path.join(root, 'ПАКЕТ_ПРЕЗЕНТАЦИИ_ИЗЛК')

const files = [
  ['01_Импорт_нового_договора', '01_Парсер_договора', 'Договор_ТЕСТ-701-ИЗЛК-СМР-2026.docx'],
  ['01_Импорт_нового_договора', '01_Парсер_договора', 'Договор_ТЕСТ-701-ИЗЛК-СМР-2026.pdf'],
  ['01_Импорт_нового_договора', '02_Хронология_договора', 'Смета_01_ТЕСТ-701-ИЗЛК-СМР-2026.xlsx'],
  ['02_Проектная_документация', '03_Проект', 'КМ_КБ-701.26.10.01.01.pdf'],
  ['02_Проектная_документация', '03_Проект', 'КЖ_КБ-701.26.10.01.01.pdf'],
  ['02_Проектная_документация', '03_Проект', 'АР_КБ-701.26.10.01.01.pdf'],
  ['03_Исполнительная_документация', '04_Исполнительная_документация', 'Акт_скрытых_работ_01_ТЕСТ-701-ИЗЛК-СМР-2026.xlsx'],
  ['03_Исполнительная_документация', '04_Исполнительная_документация', 'Паспорт_на_каркас_ТЕСТ-701-ИЗЛК-СМР-2026.docx'],
  ['03_Исполнительная_документация', '04_Исполнительная_документация', 'Сертификат_на_металл_ТЕСТ-701-ИЗЛК-СМР-2026.pdf'],
] as const

async function main() {
  for (const [group, sourceGroup, fileName] of files) {
    const folder = path.join(destination, group)
    await mkdir(folder, { recursive: true })
    await copyFile(path.join(source, sourceGroup, fileName), path.join(folder, fileName))
  }

  await writeFile(path.join(destination, 'README_НА_ПРЕЗЕНТАЦИЮ.txt'), [
    'ПАКЕТ ДЛЯ ПРЕЗЕНТАЦИИ ИЗЛК',
    '',
    '01_Импорт_нового_договора — выберите папку целиком в разделе «Импорт файлов».',
    '02_Проектная_документация — покажите автоматическое распределение КМ / КЖ / АР.',
    '03_Исполнительная_документация — покажите привязку актов, паспорта и сертификата.',
    '',
    'Важно: это копии файлов для показа. Исходные тестовые файлы не менялись.',
  ].join('\r\n'), 'utf8')

  console.log(`Пакет презентации готов: ${destination}`)
}

main().catch((error) => {
  console.error(error)
  process.exitCode = 1
})
